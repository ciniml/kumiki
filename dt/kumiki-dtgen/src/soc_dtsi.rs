//! SoC `.dtsi` generation from esp-hal's own chip description.
//!
//! Sources, both exactly the versions the firmware builds with:
//! * **esp-metadata-generated** (`src/_generated_<chip>.rs`): the chip
//!   description esp-hal is generated from — GPIO numbers, I²C / SPI master
//!   instances, and pins that may belong to embedded octal flash / PSRAM
//!   (the peripheral docs say so);
//! * the chip's **PAC** (`src/lib.rs`): peripheral base addresses
//!   (`pub type I2C0 = crate::Periph<…, 0x6001_3000>`).
//!
//! The output is the chip layer the board DTS files include; instance names
//! (`kumiki,instance`) are esp-hal's `Peripherals` field names.

use std::fmt::Write as _;

use crate::Error;

/// What the generator takes from the two sources.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct SocInfo {
    /// GPIO numbers that exist.
    pub gpios: Vec<u32>,
    /// GPIOs that embedded octal PSRAM may own.
    pub octal_psram_pins: Vec<u32>,
    /// I²C master instances (`I2C0`, …).
    pub i2c: Vec<String>,
    /// SPI master instances usable by the application (`SPI2`, …).
    pub spi: Vec<String>,
}

/// Arguments of every `<name>!((…))` invocation in `text` (the part inside
/// the double parentheses).
fn invocations<'a>(text: &'a str, name: &str) -> Vec<&'a str> {
    let pat = format!("{name}!((");
    let mut out = Vec::new();
    let mut rest = text;
    while let Some(i) = rest.find(&pat) {
        let body = &rest[i + pat.len()..];
        // Up to the matching "))" at depth 0.
        let mut depth = 0i32;
        let mut end = body.len();
        for (k, c) in body.char_indices() {
            match c {
                '(' => depth += 1,
                ')' if depth == 0 => {
                    end = k;
                    break;
                }
                ')' => depth -= 1,
                _ => {}
            }
        }
        out.push(&body[..end]);
        rest = &body[end..];
    }
    out
}

/// Parse esp-metadata-generated's chip file.
pub fn parse_metadata(text: &str) -> Result<SocInfo, Error> {
    let mut info = SocInfo::default();
    for args in invocations(text, "_for_each_inner_gpio") {
        if let Some(n) = args.split(',').next().and_then(|s| s.trim().parse::<u32>().ok())
            && !info.gpios.contains(&n)
        {
            info.gpios.push(n);
        }
    }
    for args in invocations(text, "_for_each_inner_peripheral") {
        // `@ peri_type #[doc = "…"]… GPIOn <= virtual()`
        if !args.contains("Octal SPI PSRAM") {
            continue;
        }
        if let Some(i) = args.rfind("GPIO") {
            let digits: String = args[i + 4..].chars().take_while(|c| c.is_ascii_digit()).collect();
            if let Ok(n) = digits.parse::<u32>()
                && !info.octal_psram_pins.contains(&n)
            {
                info.octal_psram_pins.push(n);
            }
        }
    }
    for args in invocations(text, "_for_each_inner_i2c_master") {
        // Individual form: `0, I2C0, I2cExt0, …`
        let f: Vec<&str> = args.split(',').map(str::trim).collect();
        if f.len() >= 2 && f[0].parse::<u32>().is_ok() && !info.i2c.contains(&f[1].to_string()) {
            info.i2c.push(f[1].to_string());
        }
    }
    for args in invocations(text, "_for_each_inner_spi_master") {
        // Detailed form: `SPI2, Spi2, FSPICLK[…] […], true`
        let f: Vec<&str> = args.split(',').map(str::trim).collect();
        if f.len() >= 3 && f[0].starts_with("SPI") && !info.spi.contains(&f[0].to_string()) {
            info.spi.push(f[0].to_string());
        }
    }
    info.gpios.sort_unstable();
    info.octal_psram_pins.sort_unstable();
    if info.gpios.is_empty() || info.i2c.is_empty() {
        return Err(Error("esp-metadata: no GPIO / I2C master entries found".into()));
    }
    Ok(info)
}

/// Base address of PAC peripheral `name` (`pub type NAME = crate::Periph<…, 0x…>;`).
pub fn pac_address(pac: &str, name: &str) -> Option<u32> {
    let pat = format!("pub type {name} = crate::Periph<");
    let i = pac.find(&pat)?;
    let rest = &pac[i + pat.len()..];
    let line = &rest[..rest.find(';')?];
    let hex = line.rsplit(',').next()?.trim().trim_end_matches('>').trim();
    u32::from_str_radix(hex.trim_start_matches("0x").replace('_', "").as_str(), 16).ok()
}

/// Generate the SoC `.dtsi` for `chip` (e.g. `esp32s3`). `sources` names
/// the inputs for the header comment.
pub fn generate(chip: &str, info: &SocInfo, pac: &str, sources: &[String]) -> Result<String, Error> {
    let addr = |name: &str| pac_address(pac, name).ok_or_else(|| Error(format!("PAC has no address for {name}")));
    let mut o = String::new();
    writeln!(o, "/*\n * {} SoC (subset used by kumiki board definitions).", chip.to_uppercase()).unwrap();
    writeln!(o, " * @generated by `kumiki-dtgen soc-dtsi` from:").unwrap();
    for s in sources {
        writeln!(o, " *   {s}").unwrap();
    }
    writeln!(o, " * Do not edit by hand.\n */\n").unwrap();
    writeln!(o, "/ {{\n\t#address-cells = <1>;\n\t#size-cells = <1>;\n\tcompatible = \"espressif,{chip}\";\n").unwrap();
    writeln!(o, "\tchosen {{\n\t}};\n").unwrap();
    writeln!(o, "\tsoc {{\n\t\t#address-cells = <1>;\n\t\t#size-cells = <1>;\n\t\tcompatible = \"simple-bus\";\n\t\tranges;").unwrap();
    let gpio = addr("GPIO")?;
    let ngpios = info.gpios.last().map(|n| n + 1).unwrap_or(0);
    writeln!(o, "\n\t\tgpio: gpio@{gpio:x} {{\n\t\t\tcompatible = \"espressif,esp32-gpio\";\n\t\t\treg = <{gpio:#x} 0x1000>;").unwrap();
    writeln!(o, "\t\t\tgpio-controller;\n\t\t\t#gpio-cells = <2>;\n\t\t\tngpios = <{ngpios}>;").unwrap();
    let missing: Vec<String> = (0..ngpios).filter(|n| !info.gpios.contains(n)).map(|n| n.to_string()).collect();
    if !missing.is_empty() {
        writeln!(o, "\t\t\t/* Not bonded out: {}. */", missing.join(" ")).unwrap();
    }
    if !info.octal_psram_pins.is_empty() {
        let pins: Vec<String> = info.octal_psram_pins.iter().map(u32::to_string).collect();
        writeln!(o, "\t\t\t/* May be owned by embedded octal PSRAM (eFuse PSRAM_CAP). */").unwrap();
        writeln!(o, "\t\t\tkumiki,octal-psram-pins = <{}>;", pins.join(" ")).unwrap();
    }
    writeln!(o, "\t\t}};").unwrap();
    let mut nodes: Vec<(String, &str, u32, &str)> = Vec::new(); // label, instance, addr, kind
    for i in &info.i2c {
        nodes.push((i.to_lowercase(), i, addr(i)?, "i2c"));
    }
    for s in &info.spi {
        nodes.push((s.to_lowercase(), s, addr(s)?, "spi"));
    }
    for (label, inst, a, kind) in &nodes {
        writeln!(o, "\n\t\t{label}: {kind}@{a:x} {{\n\t\t\tcompatible = \"espressif,esp32-{kind}\";\n\t\t\treg = <{a:#x} 0x1000>;").unwrap();
        writeln!(o, "\t\t\t#address-cells = <1>;\n\t\t\t#size-cells = <0>;\n\t\t\tkumiki,instance = \"{inst}\";\n\t\t\tstatus = \"disabled\";\n\t\t}};").unwrap();
    }
    writeln!(o, "\t}};\n}};").unwrap();
    Ok(o)
}

#[cfg(test)]
mod tests {
    use super::*;

    const META: &str = r#"
        macro_rules! for_each_gpio { () => { _for_each_inner_gpio!((0, GPIO0() () ([Input] [Output])));
        _for_each_inner_gpio!((1, GPIO1(_3 => X) () ([Input] [Output])));
        _for_each_inner_gpio!((3, GPIO3() () ([Input] [Output])));
        _for_each_inner_gpio!((all((0, GPIO0() () ([Input] [Output])))); } }
        _for_each_inner_peripheral!((@ peri_type #[doc = "GPIO3 peripheral singleton"] #[doc =
        "<li>This pin may be reserved for interfacing with Octal SPI PSRAM.</li>"] GPIO3 <= virtual()));
        _for_each_inner_peripheral!((@ peri_type #[doc = "GPIO1 peripheral singleton"] GPIO1 <= virtual()));
        _for_each_inner_i2c_master!((0, I2C0, I2cExt0, I2CEXT0_SCL, I2CEXT0_SDA));
        _for_each_inner_i2c_master!((all(0, I2C0, I2cExt0, I2CEXT0_SCL, I2CEXT0_SDA)));
        _for_each_inner_spi_master!((SPI2)); _for_each_inner_spi_master!((SPI2, Spi2, FSPICLK[FSPICS0] [FSPID], true));
    "#;
    const PAC: &str = "pub type GPIO = crate::Periph<gpio::RegisterBlock, 0x6000_4000>;\n\
        pub type I2C0 = crate::Periph<i2c0::RegisterBlock, 0x6001_3000>;\n\
        pub type SPI2 = crate::Periph<spi2::RegisterBlock, 0x6002_4000>;\n";

    #[test]
    fn parses_metadata_and_pac() {
        let info = parse_metadata(META).unwrap();
        assert_eq!(info.gpios, vec![0, 1, 3]);
        assert_eq!(info.octal_psram_pins, vec![3]);
        assert_eq!(info.i2c, vec!["I2C0"]);
        assert_eq!(info.spi, vec!["SPI2"]);
        assert_eq!(pac_address(PAC, "I2C0"), Some(0x6001_3000));
        let dtsi = generate("esp32s3", &info, PAC, &[]).unwrap();
        assert!(dtsi.contains("i2c0: i2c@60013000"));
        assert!(dtsi.contains("ngpios = <4>;"));
        assert!(dtsi.contains("Not bonded out: 2."));
        assert!(dtsi.contains("kumiki,octal-psram-pins = <3>;"));
    }
}
